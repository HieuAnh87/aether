/// Generate a proxy-config.yaml for CLIProxyAPI in `~/.config/aether/`.
///
/// Returns the path to the generated config file.
fn generate_proxy_config(port: u16, management_key: &str) -> anyhow::Result<std::path::PathBuf> {
    // Use ~/.config/aether/ (not dirs::config_dir() which returns ~/Library/Application Support
    // on macOS — the space in that path breaks CLIProxyAPI's Go flag parser).
    let home = dirs::home_dir()
        .ok_or_else(|| anyhow::anyhow!("Could not find home directory"))?;
    let aether_dir = home.join(".config").join("aether");
    std::fs::create_dir_all(&aether_dir)?;

    let config_path = aether_dir.join("proxy-config.yaml");

    let auth_dir = aether_dir.join("auth");
    std::fs::create_dir_all(&auth_dir)?;
    let auth_dir_str = auth_dir
        .to_str()
        .ok_or_else(|| anyhow::anyhow!("Auth dir path contains invalid UTF-8"))?;

    // Minimal YAML config for CLIProxyAPI
    let yaml = format!(
        r#"# Auto-generated by Aether — do not edit manually
port: {}
auth-dir: "{}"
usage-statistics-enabled: true

remote-management:
  allow-remote: false
  secret-key: "{}"
  disable-control-panel: false
"#,
        port, auth_dir_str, management_key
    );

    std::fs::write(&config_path, yaml)?;
    log::info!("Generated proxy config at {:?}", config_path);

    Ok(config_path)
}

