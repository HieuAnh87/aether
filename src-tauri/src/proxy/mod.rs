// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "lowercase")]
pub enum ProxyStatus {
    Running,
    Stopped,
    Starting,
    Restarting,
    Crashed,
}

#[derive(Debug, Clone, Serialize)]
pub struct ProxyStatusEvent {
    pub status: ProxyStatus,
    pub port: u16,
    pub error: Option<String>,
}

pub struct ProxyState {
    child: Option<CommandChild>,
    pub port: u16,
    pub status: ProxyStatus,
    health_task_abort: Option<tokio::sync::oneshot::Sender<()>>,
    /// Shared flag set to `true` just before intentionally killing the process.
    /// The background watcher reads this to distinguish graceful stop from crash.
    stopping_flag: Arc<AtomicBool>,
}

impl Default for ProxyState {
    fn default() -> Self {
        Self {
            child: None,
            port: 8317,
            status: ProxyStatus::Stopped,
            health_task_abort: None,
            stopping_flag: Arc::new(AtomicBool::new(false)),
        }
    }
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

/// Build a `ProxyStatusEvent` snapshot from the current state (must already hold the lock).
fn snapshot(state: &ProxyState) -> ProxyStatusEvent {
    ProxyStatusEvent {
        status: state.status.clone(),
        port: state.port,
        error: None,
    }
}

/// Emit a "proxy-status-changed" event to all frontend windows.
fn emit_status(app_handle: &AppHandle, event: ProxyStatusEvent) {
    if let Err(e) = app_handle.emit("proxy-status-changed", event) {
        log::warn!("Failed to emit proxy-status-changed: {}", e);
    }
}

